import type { ConstraintGroup, Domain, Layer, Syndrome, SymptomWeight } from "./types"

type Draft = {
  id: string
  name: string
  chinese: string
  pinyin: string
  layer: Layer
  domains: Domain[]
  summary: string
  reading: string
  key: [string, number][]
  support?: [string, number][]
  against?: string[]
  companions?: string[]
  implies?: string[]
  constraint?: ConstraintGroup
  pole?: string
}

const ALL: Domain[] = ["holistic", "kidney", "stomach", "dysmenorrhea"]

function weights(pairs: [string, number][] = []): SymptomWeight[] {
  return pairs.map(([id, weight]) => ({ id, weight }))
}

function draft(item: Draft): Syndrome {
  return {
    ...item,
    key: weights(item.key),
    support: weights(item.support),
    against: item.against ?? [],
    companions: item.companions ?? [],
    implies: item.implies ?? [],
  }
}

